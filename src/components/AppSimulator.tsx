"use client";

import React, { useState } from "react";
import { Smartphone, Monitor, Code2, Play, Flame, Heart, Droplets, Plus, Check, Copy } from "lucide-react";

interface AppSimulatorProps {
  title: string;
  outputData?: any;
}

export function AppSimulator({ title, outputData }: AppSimulatorProps) {
  const [activeTab, setActiveTab] = useState<"preview" | "code">("preview");
  const [device, setDevice] = useState<"mobile" | "desktop">("mobile");
  const [calories, setCalories] = useState(1840);
  const [waterGlasses, setWaterGlasses] = useState(6);
  const [copiedCode, setCopiedCode] = useState(false);

  const sampleCode = `// ${title} - Generated by Amhar's Bot
import React, { useState } from "react";
import { Heart, Flame, Droplets } from "lucide-react";

export default function App() {
  const [calories, setCalories] = useState(${calories});
  const [water, setWater] = useState(${waterGlasses});

  return (
    <div className="min-h-screen bg-slate-950 text-white p-6">
      <header className="flex justify-between items-center mb-6">
        <h1 className="text-xl font-bold text-emerald-400">${title}</h1>
        <span className="text-xs bg-emerald-500/20 text-emerald-300 px-2 py-1 rounded">Live State</span>
      </header>
      {/* Dynamic Biometrics Widget */}
      <div className="grid grid-cols-2 gap-4">
        <div className="p-4 bg-slate-900 rounded-xl">
          <p className="text-sm text-slate-400">Calories</p>
          <p className="text-2xl font-bold">{calories} / 2400 kcal</p>
        </div>
      </div>
    </div>
  );
}`;

  const copyToClipboard = () => {
    navigator.clipboard.writeText(sampleCode);
    setCopiedCode(true);
    setTimeout(() => setCopiedCode(false), 2000);
  };

  return (
    <div className="rounded-2xl border border-indigo-500/30 bg-zinc-950 p-4 shadow-2xl backdrop-blur-xl">
      {/* Header */}
      <div className="flex flex-wrap items-center justify-between gap-3 pb-3 border-b border-zinc-800">
        <div className="flex items-center gap-2">
          <div className="flex h-9 w-9 items-center justify-center rounded-lg bg-gradient-to-tr from-indigo-500 to-cyan-500 text-white shadow-md">
            <Smartphone className="h-5 w-5" />
          </div>
          <div>
            <h3 className="font-bold text-white text-sm md:text-base flex items-center gap-2">
              {title}
              <span className="rounded bg-indigo-500/20 text-indigo-300 text-[10px] px-2 py-0.5 border border-indigo-500/30 font-semibold">
                React 19 + Next.js 15
              </span>
            </h3>
            <p className="text-xs text-zinc-400">Interactive live state simulator with exportable source</p>
          </div>
        </div>

        {/* View / Device Switchers */}
        <div className="flex items-center gap-2">
          <div className="flex items-center bg-zinc-900 rounded-lg p-1 border border-zinc-800">
            <button
              onClick={() => setDevice("mobile")}
              className={`p-1.5 rounded text-xs ${
                device === "mobile" ? "bg-indigo-600 text-white" : "text-zinc-400 hover:text-white"
              }`}
              title="Mobile Device Frame"
            >
              <Smartphone className="h-3.5 w-3.5" />
            </button>
            <button
              onClick={() => setDevice("desktop")}
              className={`p-1.5 rounded text-xs ${
                device === "desktop" ? "bg-indigo-600 text-white" : "text-zinc-400 hover:text-white"
              }`}
              title="Desktop View"
            >
              <Monitor className="h-3.5 w-3.5" />
            </button>
          </div>

          <button
            onClick={() => setActiveTab(activeTab === "preview" ? "code" : "preview")}
            className="flex items-center gap-1.5 rounded-lg bg-zinc-900 px-3 py-1.5 text-xs font-semibold text-zinc-300 hover:text-white border border-zinc-800 transition-all"
          >
            {activeTab === "preview" ? (
              <>
                <Code2 className="h-3.5 w-3.5 text-indigo-400" /> View Code
              </>
            ) : (
              <>
                <Play className="h-3.5 w-3.5 text-emerald-400" /> Interactive App
              </>
            )}
          </button>
        </div>
      </div>

      {/* Simulator Display */}
      {activeTab === "preview" ? (
        <div className="mt-3 flex justify-center bg-zinc-900/40 p-4 rounded-xl border border-zinc-800/80">
          <div
            className={`transition-all duration-300 bg-slate-950 rounded-2xl border-2 border-slate-800 shadow-2xl p-4 overflow-hidden ${
              device === "mobile" ? "w-[320px] min-h-[460px]" : "w-full min-h-[380px]"
            }`}
          >
            {/* App Mock Navbar */}
            <div className="flex items-center justify-between pb-3 border-b border-slate-800">
              <span className="font-bold text-sm bg-gradient-to-r from-emerald-400 to-cyan-400 bg-clip-text text-transparent">
                AuraFit AI Pro
              </span>
              <span className="text-[10px] bg-emerald-500/20 text-emerald-400 px-2 py-0.5 rounded-full font-medium">
                Live Simulator
              </span>
            </div>

            {/* Calories Dial */}
            <div className="mt-4 p-3.5 bg-slate-900 rounded-xl border border-slate-800/80">
              <div className="flex items-center justify-between">
                <span className="text-xs text-slate-400 flex items-center gap-1">
                  <Flame className="h-3.5 w-3.5 text-rose-500" /> Daily Burn Goal
                </span>
                <span className="text-xs font-mono font-bold text-emerald-400">
                  {Math.round((calories / 2400) * 100)}%
                </span>
              </div>
              <p className="text-2xl font-black text-white font-mono mt-1">
                {calories} <span className="text-xs font-normal text-slate-400">/ 2,400 kcal</span>
              </p>
              <div className="mt-2 w-full bg-slate-800 rounded-full h-2 overflow-hidden">
                <div
                  className="bg-gradient-to-r from-emerald-500 to-cyan-400 h-full rounded-full transition-all"
                  style={{ width: `${Math.min(100, (calories / 2400) * 100)}%` }}
                />
              </div>

              {/* Action Buttons */}
              <div className="mt-3 flex items-center gap-2">
                <button
                  onClick={() => setCalories((c) => c + 150)}
                  className="flex-1 py-1 px-2 rounded-lg bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-semibold flex items-center justify-center gap-1 transition-all"
                >
                  <Plus className="h-3 w-3" /> Log Meal (+150 kcal)
                </button>
                <button
                  onClick={() => setCalories((c) => Math.max(0, c - 200))}
                  className="py-1 px-2.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-semibold transition-all"
                >
                  Burn (-200)
                </button>
              </div>
            </div>

            {/* Hydration Tracker */}
            <div className="mt-3 p-3 bg-slate-900 rounded-xl border border-slate-800/80 flex items-center justify-between">
              <div>
                <p className="text-xs text-slate-400 flex items-center gap-1">
                  <Droplets className="h-3.5 w-3.5 text-cyan-400" /> Hydration
                </p>
                <p className="text-lg font-bold text-white font-mono">{waterGlasses} Glasses</p>
              </div>
              <button
                onClick={() => setWaterGlasses((w) => w + 1)}
                className="p-1.5 rounded-lg bg-cyan-500/20 text-cyan-300 border border-cyan-500/40 hover:bg-cyan-500 hover:text-white transition-all text-xs font-semibold"
              >
                + Drink Glass
              </button>
            </div>

            {/* AI Recommendation */}
            <div className="mt-3 p-3 bg-gradient-to-r from-emerald-950/40 to-cyan-950/40 rounded-xl border border-emerald-500/20 text-xs text-slate-300">
              <span className="font-semibold text-emerald-300">AI Coach Advice:</span>
              <p className="text-[11px] text-slate-400 mt-0.5 leading-snug">
                You are on track for lean muscle recovery. Consider 25g protein post-workout.
              </p>
            </div>
          </div>
        </div>
      ) : (
        /* Code Inspector */
        <div className="mt-3 relative p-4 bg-zinc-900 rounded-xl border border-zinc-800 font-mono text-xs">
          <div className="flex items-center justify-between pb-2 mb-2 border-b border-zinc-800">
            <span className="text-indigo-400 font-semibold">src/app/page.tsx</span>
            <button
              onClick={copyToClipboard}
              className="flex items-center gap-1 text-[11px] text-zinc-400 hover:text-white px-2 py-1 bg-zinc-800 rounded border border-zinc-700 transition-all"
            >
              {copiedCode ? <Check className="h-3 w-3 text-emerald-400" /> : <Copy className="h-3 w-3" />}
              {copiedCode ? "Copied!" : "Copy Code"}
            </button>
          </div>
          <pre className="max-h-72 overflow-y-auto text-zinc-300 text-[11px] leading-relaxed">
            {sampleCode}
          </pre>
        </div>
      )}
    </div>
  );
}
